def _guess_unit(name: str) -> str:
    n = name.lower()
    if "яйц" in n:
        return "шт"
    if any(x in n for x in ["молоко", "вода", "масло", "соус", "сливк", "кефир", "йогурт"]):
        return "мл"
    return "г"


